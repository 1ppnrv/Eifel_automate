SELECT
       -- e1.ID_SOCIETE AS ID_CLIENT,
       cl.SOCIETE_RAISON_SOCIALE AS CLIENT,
       -- pr.ID_CLASSE_PRINCIPALE AS ID_FAMILLE, 
       -- pr.ID_CLASSE_SECONDAIRE AS ID_SOUS_FAMILLE, 
       fa.OBJET_LIBELLE  AS FAMILLE, 
       -- ssfa.OBJET_LIBELLE  AS SOUS_FAMILLE,
       pr.OBJET_LIBELLE AS PRODUIT,
       -- unite.CONDITIONNEMENT_TYPE_CLE AS UNITE,
       -- SUM(e1.ECRITURE_MONTANT_HT) AS CA, 
       -- SUM(e1.ECRITURE_QUANTITE) AS QTE,
       -- SUM(mvt.REEL_PIECE * DIF(SCOMPARE(e1.IDS_JOURNAL_TYPE,'1' ),1,-1)) AS PIECE,  
       SUM(mvt.REEL_KILO   * DIF(SCOMPARE(e1.IDS_JOURNAL_TYPE,'1' ),1,-1)) AS KILO
       -- SUM(mvt.REEL_COLIS * DIF(SCOMPARE(e1.IDS_JOURNAL_TYPE,'1' ),1,-1)) AS COLIS,
       -- SUM(case mvt.IDS_CONDITIONNEMENT_TYPE when '2' then mvt.REEL_KILO when '1' then mvt.REEL_COLIS else mvt.REEL_PIECE end * DIF(SCOMPARE(e1.IDS_JOURNAL_TYPE,'1' ),1,-1)) AS QTE_FAC,
       -- RFLOAT(MULDIV(SUM(e1.ECRITURE_MONTANT_HT),1,SUM(e1.ECRITURE_QUANTITE)),2) AS PRIX_MOYEN
FROM ECRITURE e1 left join commande c on (c.ip_commande=e1.id_commande)
      LEFT OUTER JOIN OBJET pr ON        (pr.IP_OBJET = e1.ID_OBJET)
      LEFT OUTER JOIN OBJET fa ON        (fa.IP_OBJET = pr.ID_CLASSE_PRINCIPALE)
      LEFT OUTER JOIN OBJET ssfa ON     (ssfa.IP_OBJET = pr.ID_CLASSE_SECONDAIRE)
      LEFT OUTER JOIN SOCIETE ce ON    (ce.Ip_SOCIETE = e1.ID_CENTRALE)
      LEFT OUTER JOIN SOCIETE cl ON     (cl.Ip_SOCIETE = e1.ID_SOCIETE )
      LEFT OUTER JOIN MOUVEMENT mvt ON  (mvt.ID_COMMANDE_DETAIL = e1.ID_COMMANDE_DETAIL and (mvt.id_objet_relation=0))
      LEFT OUTER JOIN SYS_CONDITIONNEMENT_TYPE unite ON (unite.IP_CONDITIONNEMENT_TYPE = mvt.IDS_CONDITIONNEMENT_TYPE)
WHERE 
       ( e1.ID_MASTER = 1)
       AND ( e1.IDS_JOURNAL_TYPE = '1' )
       AND ( e1.IDS_CLASSE_TYPE = 'A' ) and (c.ids_commande_type in ('0','6'))
       AND ( e1.ECRITURE_DATE_COMMANDE  BETWEEN 'date1' AND 'date1 23:59')




GROUP BY 
         pr.ID_CLASSE_PRINCIPALE, 
         pr.ID_CLASSE_SECONDAIRE, 
         fa.OBJET_LIBELLE, 
         ssfa.OBJET_LIBELLE,
         pr.OBJET_LIBELLE,
         e1.ID_SOCIETE,
         cl.SOCIETE_RAISON_SOCIALE,
         unite.CONDITIONNEMENT_TYPE_CLE 
ORDER BY 
         fa.OBJET_LIBELLE,
         ssfa.OBJET_LIBELLE,
         pr.OBJET_LIBELLE,
         cl.SOCIETE_RAISON_SOCIALE,
         e1.ID_SOCIETE